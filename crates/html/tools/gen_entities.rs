//! Generates `src/entities/table.rs`, the named character reference table,
//! from the WHATWG `entities.json` (spec 0004, child 0002, Tokenizer).
//!
//! Run by hand when the standard's table changes, then commit the output.
//! It needs only `std`, so it builds with plain `rustc`:
//!
//! ```text
//! curl -o /tmp/entities.json https://html.spec.whatwg.org/entities.json
//! rustc --edition 2024 -O tools/gen_entities.rs -o /tmp/gen_entities
//! /tmp/gen_entities /tmp/entities.json > src/entities/table.rs
//! ```
//!
//! `entities.json` keeps one entry per line,
//! `"&AElig": { "codepoints": [198], "characters": "Æ" },`, so a line
//! reader is enough and no JSON parser is needed.

use std::fmt::Write as _;
use std::process::ExitCode;

fn main() -> ExitCode {
    let Some(path) = std::env::args().nth(1) else {
        eprintln!("usage: gen_entities <entities.json>");
        return ExitCode::FAILURE;
    };
    let json = match std::fs::read_to_string(&path) {
        Ok(json) => json,
        Err(error) => {
            eprintln!("cannot read {path}: {error}");
            return ExitCode::FAILURE;
        }
    };
    let mut entries = Vec::new();
    for (number, line) in json.lines().enumerate() {
        let Some(start) = line.find("\"&") else {
            continue;
        };
        match parse_entry(&line[start + 2..]) {
            Some(entry) => entries.push(entry),
            None => {
                eprintln!("line {}: not an entry: {line}", number + 1);
                return ExitCode::FAILURE;
            }
        }
    }
    entries.sort_by(|a, b| a.0.cmp(&b.0));
    entries.dedup_by(|a, b| a.0 == b.0);

    let mut out = String::new();
    out.push_str(
        "//! The named character reference table: generated by\n\
         //! `tools/gen_entities.rs` from the WHATWG `entities.json`. Do not edit.\n\n",
    );
    let _ = writeln!(
        out,
        "/// `(name, replacement)`, sorted by name; {} entries. Names without\n\
         /// `;` are the legacy forms the standard also accepts.",
        entries.len()
    );
    out.push_str("pub(crate) static ENTITIES: &[(&str, &str)] = &[\n");
    for (name, replacement) in &entries {
        let _ = writeln!(out, "    (\"{name}\", \"{replacement}\"),");
    }
    out.push_str("];\n");
    print!("{out}");
    ExitCode::SUCCESS
}

/// `AElig": { "codepoints": [198], ... }` to `("AElig", "\u{C6}")`.
fn parse_entry(rest: &str) -> Option<(String, String)> {
    let (name, rest) = rest.split_once('"')?;
    if name.is_empty() || !name.chars().all(|c| c.is_ascii_alphanumeric() || c == ';') {
        return None;
    }
    let (_, rest) = rest.split_once('[')?;
    let (codepoints, _) = rest.split_once(']')?;
    let mut replacement = String::new();
    for code in codepoints.split(',') {
        let code: u32 = code.trim().parse().ok()?;
        let c = char::from_u32(code)?;
        match c {
            '"' | '\\' => {
                replacement.push('\\');
                replacement.push(c);
            }
            c if c.is_ascii_graphic() || c == ' ' => replacement.push(c),
            c => {
                let _ = write!(replacement, "\\u{{{:X}}}", u32::from(c));
            }
        }
    }
    Some((name.to_owned(), replacement))
}
